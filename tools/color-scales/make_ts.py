"""Writes src/data/colorScaleData.ts from scales.json (made by build_scales.py).

Run from this folder:  python build_scales.py && python check_palettes.py && python make_ts.py
"""
import json, pathlib

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent.parent / 'src' / 'data' / 'colorScaleData.ts'
KEYS = {'surface_temperature': 'surfaceTemperature', 'temperature_925': 'temperature925',
        'temperature_850': 'temperature850', 'wind_500': 'wind500', 'wind_250': 'wind250',
        'cape': 'cape', 'precipitation': 'precipitation',
        'precipitable_water': 'precipitableWater', 'snowfall': 'snowfallTotal'}

S = json.load(open(HERE / 'scales.json', encoding='utf-8'))
lines = [
    "// Color scales for the core products (Week 4, approved Nov 7, 2026).",
    "// Generated by tools/color-scales/make_ts.py: each unit option has its own",
    "// round-number breakpoints (display units) and the same colors for the same",
    "// physical value. Edit the palettes in build_scales.py and regenerate, so the",
    "// colorblind and basemap checks (check_palettes.py) stay valid.",
    "// Reflectivity isn't here: IEM tiles arrive already colored.",
    "",
    "import type { DisplayUnit } from '../lib/units'",
    "",
    "export interface ScaleDef {",
    "  breakpoints: number[] // lower edge of each band, in display units",
    "  colors: string[] // one hex color per band",
    "  hideBelow: boolean // true: values under the first breakpoint aren't drawn",
    "}",
    "",
    "export type ScaleKey =",
    *[f"  | '{k}'" for k in KEYS.values()],
    "",
    "export const SCALES: Record<ScaleKey, Partial<Record<DisplayUnit, ScaleDef>>> = {",
]
for key, p in S.items():
    lines.append(f"  {KEYS[key]}: {{")
    for unit, d in p['units'].items():
        hide = d['alpha'][0] == 0
        colors = d['colors'][1:] if hide else d['colors']
        lines += [f"    '{unit}': {{",
                  f"      breakpoints: [{', '.join('%g' % b for b in d['breakpoints'])}],",
                  f"      colors: [{', '.join(repr(c) for c in colors)}],",
                  f"      hideBelow: {'true' if hide else 'false'},",
                  "    },"]
    lines.append("  },")
lines.append("}")
OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('wrote', OUT)
